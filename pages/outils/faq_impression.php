<div class="attr RESOLUTION">


<p>L'option d'impression de l'arrière-plan est désactivée dans la plupart des navigateurs Web. Lorsqu'une page de photos est créée par iWeb, les vignettes sont définies comme arrière-plans et n'apparaissent pas lors de l'impression avec les réglages par défaut du navigateur.</p>
<h4>Activer l'impression d'arrière-plan dans Safari</h4>
<p>&nbsp;</p>
<ol>
    <li>Dans la page que vous souhaitez imprimer, choisissez <strong>Fichier &gt; Imprimer</strong>.</li>
    <li>Choisissez <strong>Safari</strong> dans le menu déroulant de la boîte de dialogue d'impression dans lequel l'option «&nbsp;Copies et pages&nbsp;» est sélectionnée par défaut.</li>
    <li>Sélectionnez la case à cocher «&nbsp;Imprimer les arrière-plans&nbsp;» et décocher «&nbsp;Impression : En-têtes et pieds de page&nbsp;».</li>
</ol>
<p><img data-hires="true" src="../images/support/305157_1-fr.png" alt="" height="250" width="583"></p>
<h4>Activer l'impression d'arrière-plan dans Firefox pour Mac</h4>
<p>&nbsp;</p>
<ol>
    <li>Dans la page que vous souhaitez imprimer, choisissez <strong>Fichier &gt; Imprimer</strong>.</li>
    <li>Choisissez <strong>Firefox</strong> dans le menu déroulant de la boîte de dialogue d'impression dans lequel l'option «&nbsp;Copies et pages&nbsp;» est sélectionnée par défaut.</li>
    <li>Sélectionnez la case à cocher «&nbsp;Imprimer les arrière-plans&nbsp;».</li>
</ol>
<h4>Activer l'impression d'arrière-plan dans Internet Explorer pour Windows</h4>
<ol>
    <li>Ouvrez Options Internet dans le Panneau de configuration.</li>
    <li>Cliquez sur l’onglet Avancés.</li>
    <li>Faites défiler pour accéder à l'en-tête Impression, puis sélectionnez la case à cocher «&nbsp;Imprimer les couleurs et les images d'arrière-plan&nbsp;».</li>
    <li>Cliquez sur Appliquer.</li>
</ol>
<p><img data-hires="true" src="../images/support/305157_2-fr.jpg" alt=""></p>
<h4>Activer l'impression d'arrière-plan dans Firefox pour Windows</h4>
<ol>
    <li>Choisissez <strong>Fichier &gt; Mise en page</strong>.</li>
    <li>Cliquez sur l'onglet Format et options.</li>
    <li>Sélectionnez la case à cocher «&nbsp;Imprimer le fond de page (couleurs et images)&nbsp;».</li>
    <li>Cliquez sur OK.</li>
</ol>
<p>Pour activer l'impression d'arrière-plan dans d'autres navigateurs Web, veuillez consulter la documentation de votre navigateur.</p>
